def test_framework_mode_missing_hook_types(tmp_path, git_env):
    path = tmp_path / "fw"
    path.mkdir()
    git(path, "init", "-q")
    write(
        path / ".pre-commit-config.yaml",
        "repos:\n  - repo: https://github.com/AleBrito124356/git-hooks-collection\n"
        "    rev: v0.1.0\n    hooks:\n      - id: githooks-secrets\n"
        "      - id: githooks-conventional-commit\n",
    )
    write(path / ".git" / "hooks" / "pre-commit", "#!/bin/sh\n# File generated by pre-commit\n")
    rc, out = doctor(path)
    assert rc == 1
    assert "pre-commit: pre-commit hook installed (secrets)" in out
    assert (
        "commit-msg hook type is not installed. Fix: pre-commit install --hook-type commit-msg"
        in out
    )
    assert "rev v0.1.0 was never released" in out


def test_pinned_rev_resolves_in_the_source_repository(tmp_path, git_env):
    path = tmp_path / "pc"
    path.mkdir()
    git(path, "init", "-q")
    result = install(path, "--mode", "pre-commit", "--hooks", "secrets", "--repo-url", str(ROOT))
    assert result.rc == 0, result.out
    text = (path / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    rev = text.split("rev:", 1)[1].split()[0]
    assert git(ROOT, "cat-file", "-e", f"{rev}^{{commit}}", check=False).returncode == 0
    assert f"repo: {ROOT}" in text
